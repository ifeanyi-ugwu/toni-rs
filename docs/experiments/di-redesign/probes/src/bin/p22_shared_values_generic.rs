//! P22 (transports X2): `#[routes]` cannot name the type of an impl-level `value = expr`, so the
//! generated `__FwShared` carries one type parameter per value, in the order written, and `mount`
//! infers them from the expressions. Each per-handler mount fn takes `&__FwShared<..>` with the
//! role bound for its own transport, clones the `Arc` and unsizes it to that transport's role
//! object; one value serves two transports and the role check runs per handler. Expected:
//! compiles, prints "strong count 3; http sees http-limit; rpc sees rpc-limit".
#![allow(non_upper_case_globals)]
use std::sync::Arc;

pub trait Transport: 'static {}
pub struct Http;
pub struct Rpc;
impl Transport for Http {}
impl Transport for Rpc {}

pub trait Guard<T: Transport>: Send + Sync + 'static {
    fn name(&self) -> &'static str;
}
pub type AnyGuard<T> = dyn Guard<T>;

pub struct RateLimit(pub u32);
impl Guard<Http> for RateLimit {
    fn name(&self) -> &'static str {
        "http-limit"
    }
}
impl Guard<Rpc> for RateLimit {
    fn name(&self) -> &'static str {
        "rpc-limit"
    }
}

/// `EnhancerSpec::guard_arc`: the unsizing happens where `G` is concrete, as `widen_guard` does today.
pub struct Spec<T: Transport> {
    guards: Vec<Arc<AnyGuard<T>>>,
}
impl<T: Transport> Spec<T> {
    fn new() -> Self {
        Spec { guards: Vec::new() }
    }
    fn guard_arc<G: Guard<T>>(&mut self, guard: Arc<G>) {
        let widened: Arc<AnyGuard<T>> = guard;
        self.guards.push(widened);
    }
}

// Generated by `#[routes]`: one field per impl-level `value = ..`, typed by a parameter.
pub struct __FwShared<V0> {
    v0: Arc<V0>,
}

pub struct Ctl;

impl Ctl {
    // Generated by `#[fw_http::get]` from the `__handler` tokens, whose controller tier carries
    // `value = ..` as entry 0: the bound names the role for this handler's transport.
    fn __fw_mount_get<V0: Guard<Http>>(shared: &__FwShared<V0>) -> Spec<Http> {
        let mut spec = Spec::new();
        spec.guard_arc(Arc::clone(&shared.v0));
        spec
    }

    // Generated by `#[fw_rpc::message]`: the same value, this transport's role.
    fn __fw_mount_get_rpc<V0: Guard<Rpc>>(shared: &__FwShared<V0>) -> Spec<Rpc> {
        let mut spec = Spec::new();
        spec.guard_arc(Arc::clone(&shared.v0));
        spec
    }

    // Generated by `#[routes]`: the value is built once; the type parameter is inferred here.
    fn mount() -> (Spec<Http>, Spec<Rpc>, usize) {
        let shared = __FwShared { v0: Arc::new(RateLimit(20)) };
        let http = Self::__fw_mount_get(&shared);
        let rpc = Self::__fw_mount_get_rpc(&shared);
        (http, rpc, Arc::strong_count(&shared.v0))
    }
}

fn main() {
    let (http, rpc, count) = Ctl::mount();
    println!(
        "strong count {count}; http sees {}; rpc sees {}",
        http.guards[0].name(),
        rpc.guards[0].name()
    );
}
